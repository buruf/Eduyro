// scripts/build-lesson-voice-local.mjs
// Free, offline narration for the 20 × 3 explainer using the Windows built-in
// speech engine, then regenerates src/remotion/lesson/voice-manifest.ts with
// each clip's real duration so the video timeline fits the speech.
//
//   node scripts/build-lesson-voice-local.mjs
//
// Why not the browser's speechSynthesis: it only plays to the speakers, it
// cannot produce a file, so Remotion has nothing to encode into the MP4. This
// uses the same idea (a free local voice) but writes real WAVs.
//
// For the good voice, use scripts/build-lesson-voice.mjs (ElevenLabs) instead.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { join } from "node:path";
import { tmpdir } from "node:os";

const ROOT = process.cwd();
const OUT_DIR = join(ROOT, "public", "lesson-voice");
const MANIFEST = join(ROOT, "src", "remotion", "lesson", "voice-manifest.ts");

// Mirrors src/remotion/lesson/script.ts, normalised for a basic TTS engine:
// "×" spoken as "times", and "…" as a comma, which it renders as a pause.
const LINES = [
  { id: "ask", text: "So, what does 20 times 3 actually mean?" },
  {
    id: "groups",
    text: "It means 3 groups of 20. Here's one group, 10 yellow, and 10 blue. That's 20. Now another one. And one more.",
  },
  { id: "count", text: "Let's count them up. 20, 40, 60. So that's 20 plus 20 plus 20, which is 60. And 20 times 3 means exactly the same thing." },
  {
    id: "trick",
    text: "But here's a faster way. Cover up the zero, 2 times 3 is 6. Now put the zero back on, 60. Same answer, much quicker.",
  },
];

/** Duration of a PCM WAV, read from its own header (no ffprobe needed). */
function wavDurationSeconds(path) {
  const buf = readFileSync(path);
  if (buf.length < 44 || buf.toString("ascii", 0, 4) !== "RIFF") {
    throw new Error(`not a WAV: ${path}`);
  }
  let byteRate = 0;
  let dataSize = 0;
  let off = 12; // past "RIFF" + size + "WAVE"
  while (off + 8 <= buf.length) {
    const id = buf.toString("ascii", off, off + 4);
    const size = buf.readUInt32LE(off + 4);
    if (id === "fmt ") byteRate = buf.readUInt32LE(off + 16);
    if (id === "data") { dataSize = size; break; }
    off += 8 + size + (size % 2); // chunks are word-aligned
  }
  if (!byteRate || !dataSize) throw new Error(`could not read WAV header: ${path}`);
  return dataSize / byteRate;
}

mkdirSync(OUT_DIR, { recursive: true });

const linesJson = join(tmpdir(), `lesson-lines-${Date.now()}.json`);
writeFileSync(linesJson, JSON.stringify(LINES), "utf8");

console.log("Synthesizing with the Windows speech engine…");
const out = execFileSync(
  "powershell",
  [
    "-NoProfile",
    "-ExecutionPolicy", "Bypass",
    "-File", join(ROOT, "scripts", "tts-windows.ps1"),
    "-LinesJson", linesJson,
    "-OutDir", OUT_DIR,
    "-Rate", "0",
  ],
  { encoding: "utf8" },
);
console.log(out.trim());

const clips = LINES.map((line) => {
  const path = join(OUT_DIR, `${line.id}.wav`);
  if (!existsSync(path)) throw new Error(`missing ${path} — synthesis failed`);
  const durationInSeconds = Number(wavDurationSeconds(path).toFixed(3));
  console.log(`  ${line.id}: ${durationInSeconds.toFixed(1)}s`);
  return { id: line.id, file: `lesson-voice/${line.id}.wav`, durationInSeconds };
});

writeFileSync(
  MANIFEST,
  `// src/remotion/lesson/voice-manifest.ts
// GENERATED by scripts/build-lesson-voice-local.mjs — do not hand-edit.
export interface VoiceClip {
  id: string;
  file: string; // relative to public/
  durationInSeconds: number;
}

export const VOICE_CLIPS: VoiceClip[] = ${JSON.stringify(clips, null, 2)};
`,
);

const total = clips.reduce((n, c) => n + c.durationInSeconds, 0);
console.log(`\n${clips.length} clips, ${total.toFixed(1)}s of speech. Wrote voice-manifest.ts`);
console.log("Render:  npx remotion render MulTens out/20x3.mp4");
