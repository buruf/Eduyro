// scripts/build-lesson-voice.mjs
// Synthesizes the 20 × 3 explainer's narration into public/lesson-voice/*.mp3
// and regenerates src/remotion/lesson/voice-manifest.ts with the real clip
// durations, so the video timeline stretches each scene to fit its line.
//
//   node scripts/build-lesson-voice.mjs
//
// Needs ELEVENLABS_API_KEY and ELEVENLABS_VOICE_ID in .env.local. Those are
// marked sensitive in Vercel, so `vercel env pull` cannot fetch them — they
// have to be pasted into .env.local by hand, once.
//
// Uses the /with-timestamps endpoint because it returns per-character timings,
// which give the EXACT clip duration without having to probe the mp3.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { join } from "node:path";

const ROOT = process.cwd();
const VOICE_KEY = process.env.VOICE_KEY ?? "main";
const OUT_DIR = join(ROOT, "public", "lesson-voice", VOICE_KEY);
const MANIFEST = join(ROOT, "src", "remotion", "lesson", "voice-manifest.ts");

// --- env -------------------------------------------------------------------
for (const file of [".env.local", ".env"]) {
  const p = join(ROOT, file);
  if (!existsSync(p)) continue;
  for (const line of readFileSync(p, "utf8").split("\n")) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*"?([^"\r\n]*)"?\s*$/);
    if (m && process.env[m[1]] === undefined) process.env[m[1]] = m[2];
  }
}

const API_KEY = process.env.ELEVENLABS_API_KEY;
const VOICE_ID = process.env.ELEVENLABS_VOICE_ID;
const MODEL_ID = process.env.ELEVENLABS_MODEL_ID ?? "eleven_turbo_v2_5";

if (!API_KEY || !VOICE_ID) {
  console.error(
    [
      "Missing ELEVENLABS_API_KEY and/or ELEVENLABS_VOICE_ID.",
      "",
      "Add them to .env.local (they are sensitive in Vercel, so they cannot be pulled):",
      "  ELEVENLABS_API_KEY=...",
      "  ELEVENLABS_VOICE_ID=...",
      "",
      "Then re-run: node scripts/build-lesson-voice.mjs",
    ].join("\n"),
  );
  process.exit(1);
}

// --- the script ------------------------------------------------------------
// Mirrors src/remotion/lesson/script.ts. Kept as plain data here so this file
// runs under plain node with no TS tooling.
const LINES = [
  { id: "ask", text: "So… what does 20 times 3 actually mean?" },
  {
    id: "groups",
    text: "It means 3 groups of 20. Here's one group… 10 yellow, and 10 blue. That's 20. Now another one. And one more.",
  },
  {
    id: "count",
    text: "Let's count them up. 20… 40… 60. So that's 20 plus 20 plus 20, which is 60. And 20 times 3 means exactly the same thing.",
  },
  {
    id: "trick",
    text: "But here's a faster way. Cover up the zero… 2 times 3 is 6. Now put the zero back on… 60. Same answer, much quicker.",
  },
];

// Matches VOICE_PRESETS.lively in src/lib/tts/elevenlabs.ts — 0.7 is the
// slowest the API allows, which is where the app's narration landed.
const VOICE_SETTINGS = {
  stability: 0.45,
  similarity_boost: 0.85,
  style: 0.45,
  use_speaker_boost: true,
  speed: 0.7,
};

async function synthesize(text) {
  const res = await fetch(
    `https://api.elevenlabs.io/v1/text-to-speech/${VOICE_ID}/with-timestamps`,
    {
      method: "POST",
      headers: {
        "xi-api-key": API_KEY,
        "Content-Type": "application/json",
        Accept: "application/json",
      },
      body: JSON.stringify({ text, model_id: MODEL_ID, voice_settings: VOICE_SETTINGS }),
    },
  );
  if (!res.ok) {
    throw new Error(`ElevenLabs ${res.status}: ${(await res.text()).slice(0, 200)}`);
  }
  const j = await res.json();
  const mp3 = Buffer.from(j.audio_base64 ?? j.audio ?? "", "base64");
  const ends =
    j.alignment?.character_end_times_seconds ??
    j.normalized_alignment?.character_end_times_seconds ??
    [];
  const duration = ends.length ? ends[ends.length - 1] : 0;
  if (!mp3.length) throw new Error("empty audio returned");
  return { mp3, duration };
}

mkdirSync(OUT_DIR, { recursive: true });

const clips = [];
for (const line of LINES) {
  process.stdout.write(`  ${line.id}… `);
  const { mp3, duration } = await synthesize(line.text);
  const file = `lesson-voice/${VOICE_KEY}/${line.id}.mp3`;
  writeFileSync(join(OUT_DIR, `${line.id}.mp3`), mp3);
  clips.push({ id: line.id, file, durationInSeconds: Number(duration.toFixed(3)) });
  console.log(`${duration.toFixed(1)}s`);
}

// Merge into whatever voices are already generated — running this for one
// voice must never drop another voice's clips.
let byVoice = {};
if (existsSync(MANIFEST)) {
  const prev = readFileSync(MANIFEST, "utf8");
  const start = prev.indexOf("= {", prev.indexOf("VOICE_CLIPS_BY_VOICE"));
  const end = prev.lastIndexOf("};");
  if (start !== -1 && end > start) {
    try {
      byVoice = JSON.parse(prev.slice(start + 2, end + 1));
    } catch {
      console.warn("  (could not parse existing manifest — rewriting it)");
    }
  }
}
byVoice[VOICE_KEY] = clips;

const header = [
  "// src/remotion/lesson/voice-manifest.ts",
  "// GENERATED by scripts/build-lesson-voice.mjs — do not hand-edit.",
  "export interface VoiceClip {",
  "  id: string;",
  "  file: string; // relative to public/",
  "  durationInSeconds: number;",
  "}",
  "",
  "export const VOICE_CLIPS_BY_VOICE: Record<string, VoiceClip[]> =",
].join("\n");

writeFileSync(MANIFEST, `${header} ${JSON.stringify(byVoice, null, 2)};\n`);

const total = clips.reduce((n, c) => n + c.durationInSeconds, 0);
console.log(`\n${clips.length} clips, ${total.toFixed(1)}s of speech.`);
console.log(`Voices in manifest: ${Object.keys(byVoice).join(", ")}`);
console.log(`Render:  npx remotion render MulTens out/mul-tens.${VOICE_KEY}.mp4 --props='{"voice":"${VOICE_KEY}"}'`);
